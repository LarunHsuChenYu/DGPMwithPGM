/* ---------- CHANGE_PASSWORD_HISTORY：變更／重設密碼記錄（Login） ---------- */
IF OBJECT_ID(N'dbo.CHANGE_PASSWORD_HISTORY', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.CHANGE_PASSWORD_HISTORY
    (
        LOG_ID    BIGINT         IDENTITY(1,1) NOT NULL,
        USER_ID   VARCHAR(10)    NOT NULL,
        PASSWORD  VARCHAR(500)   NOT NULL,  -- 新密碼 hash
        LOG_DATE  DATE           NOT NULL,
        CONSTRAINT PK_CHANGE_PASSWORD_HISTORY PRIMARY KEY CLUSTERED (LOG_ID)
