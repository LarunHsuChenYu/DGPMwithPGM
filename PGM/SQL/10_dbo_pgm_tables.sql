        CRT_DATE  DATETIME      NOT NULL,
        CRT_USER  NVARCHAR(10)  NOT NULL,
        CONSTRAINT PK_MAP_USER_ROLE PRIMARY KEY CLUSTERED (USER_ID, ROLE_ID)
    );
END
GO

/* ---------- SET_FUNCTION：功能主檔（BMW + SysFun 擴充欄；取代 SysFun 表） ---------- */
IF OBJECT_ID(N'dbo.SET_FUNCTION', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.[SET_FUNCTION]
    (
        /* BMW 基底 */
        FUNCTION_ID    VARCHAR(20)     NOT NULL,
        FUNCTION_NAME  NVARCHAR(50)    NOT NULL,
        FUNCTION_URL   NVARCHAR(100)   NULL,
        PARENT_NAME    VARCHAR(20)     NULL,   -- 大類顯示名（SRS Login 選單用）
        SORT_ID        SMALLINT        NOT NULL CONSTRAINT DF_SET_FUNCTION_SORT_ID DEFAULT (0),
        DEL_FLG        BIT             NOT NULL CONSTRAINT DF_SET_FUNCTION_DEL_FLG DEFAULT (0),
        CRT_DATE       DATETIME        NOT NULL,
        CRT_USER       NVARCHAR(10)    NOT NULL,
        MDF_DATE       DATETIME        NULL,
        MDF_USER       NVARCHAR(10)    NULL,

        /* SysFun 擴充（階層／選單語意；表名仍為 SET_FUNCTION） */
        PARENT_ID      VARCHAR(20)     NULL,   -- 上層 FUNCTION_ID；模組列為 NULL
        ACTION_TYPE    CHAR(1)         NOT NULL CONSTRAINT DF_SET_FUNCTION_ACTION_TYPE DEFAULT ('P'),
        IS_MENU        CHAR(1)         NOT NULL CONSTRAINT DF_SET_FUNCTION_IS_MENU DEFAULT ('N'),
        IS_ENABLED     CHAR(1)         NOT NULL CONSTRAINT DF_SET_FUNCTION_IS_ENABLED DEFAULT ('Y'),
        FUN_DESC       NVARCHAR(500)   NULL,
        ICON           NVARCHAR(50)    NULL,
        SYSTEM_CODE    VARCHAR(20)     NOT NULL CONSTRAINT DF_SET_FUNCTION_SYSTEM_CODE DEFAULT ('PGM'),

        CONSTRAINT PK_SET_FUNCTION PRIMARY KEY CLUSTERED (FUNCTION_ID),
        CONSTRAINT CK_SET_FUNCTION_ACTION_TYPE CHECK (ACTION_TYPE IN ('M', 'P', 'B')),
        CONSTRAINT CK_SET_FUNCTION_IS_MENU CHECK (IS_MENU IN ('Y', 'N')),
        CONSTRAINT CK_SET_FUNCTION_IS_ENABLED CHECK (IS_ENABLED IN ('Y', 'N'))
    );

    CREATE NONCLUSTERED INDEX IX_SET_FUNCTION_PARENT_SORT
        ON dbo.[SET_FUNCTION] (PARENT_ID, SORT_ID, FUNCTION_ID)
        WHERE DEL_FLG = 0;

    CREATE NONCLUSTERED INDEX IX_SET_FUNCTION_MENU
        ON dbo.[SET_FUNCTION] (SORT_ID, FUNCTION_ID)
        WHERE DEL_FLG = 0 AND IS_MENU = 'Y' AND IS_ENABLED = 'Y';

    CREATE NONCLUSTERED INDEX IX_SET_FUNCTION_SYSTEM_CODE
        ON dbo.[SET_FUNCTION] (SYSTEM_CODE, DEL_FLG, IS_MENU, IS_ENABLED, SORT_ID, FUNCTION_ID);
END
GO

IF OBJECT_ID(N'dbo.[SET_FUNCTION]', N'U') IS NOT NULL
   AND COL_LENGTH(N'dbo.[SET_FUNCTION]', N'SYSTEM_CODE') IS NULL
BEGIN
    ALTER TABLE dbo.[SET_FUNCTION] ADD SYSTEM_CODE VARCHAR(20) NOT NULL
        CONSTRAINT DF_SET_FUNCTION_SYSTEM_CODE DEFAULT ('PGM');
END
GO

