/* =============================================================================
   10_dbo_pgm_tables.sql
   PGM — 依 BMW LIST（BMWv20260720）＋四份 SRS 建立資料表

   收錄表（LIST）：
     EMP_USER, EMP_ORG, DIM_ROLE, MAP_USER_ROLE,
     SET_FUNCTION, MAP_ROLE_FUNCTION,
     SET_PARAMITEM, SET_PARAM, CHANGE_PASSWORD_HISTORY,
     AUTHENTICATION_LOG（登入流程必要；非 BMW LIST）

   不實作：DIM_RIGHT、MAP_ROLE_RUNCTION（LIST 未收錄／SRS 未用）

   SET_FUNCTION：
     - 基底欄位依 BMW
     - 擴充 SysFun 語意欄位（PARENT_ID / ACTION_TYPE / IS_MENU / IS_ENABLED /
       FUN_DESC / ICON），表名維持 SET_FUNCTION（不以 SysFun 建表）

   EMP_USER.DPT_CODE：
     - 專案／SA 增補，關聯 EMP_ORG.DPT_CODE（nvarchar(10)，允許 NULL）
     - 建表順序：EMP_ORG 須先於 EMP_USER（含 FK）

   可重複執行（表不存在才建立；既有庫缺欄／缺 FK 則補）。

   SET_* 表名：T-SQL 保留字前綴，物件參考一律用方括號（dbo.[SET_FUNCTION]）。
   本檔為 UTF-8 BOM；SSMS 請以 UTF-8 開啟，勿當 Big5／系統預設編碼。
   ============================================================================= */

SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

USE [PGM_DEV];
GO

/* ---------- EMP_ORG：組織單位資料檔（僅 DDL 預留，本階段無維護 UI） ---------- */
IF OBJECT_ID(N'dbo.EMP_ORG', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.EMP_ORG
    (
        DPT_CODE     NVARCHAR(10)   NOT NULL,
        DPT_NO       NVARCHAR(6)    NOT NULL,
        DPTCD_NAME   NVARCHAR(50)   NOT NULL,
        DPTCD_ENAME  NVARCHAR(200)  NULL,
        CODE_BOSS    NVARCHAR(10)   NOT NULL,
        DPT_LEVE     NVARCHAR(1)    NOT NULL,
        UPPER_DPT    NVARCHAR(6)    NOT NULL,
        CRT_DATE     DATETIME       NOT NULL,
        CRT_USER     NVARCHAR(50)   NOT NULL,
        MDF_DATE     DATETIME       NULL,
        MDF_USER     NVARCHAR(50)   NULL,
        CONSTRAINT PK_EMP_ORG PRIMARY KEY CLUSTERED (DPT_CODE)
    );
END
GO

/* ---------- EMP_USER：使用者帳號維護檔（Login／EMPSet） ---------- */
IF OBJECT_ID(N'dbo.EMP_USER', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.EMP_USER
    (
        USER_ID    VARCHAR(10)    NOT NULL,
        USER_NAME  NVARCHAR(100)  NOT NULL,
        DPT_CODE   NVARCHAR(10)   NULL,       -- 關聯 EMP_ORG；允許 NULL（種子可未填）
        PASSWORD   VARCHAR(500)   NOT NULL,  -- BCrypt hash
        EMAIL      NVARCHAR(255)  NULL,
        TELEPHONE  NVARCHAR(50)   NULL,
        DEL_FLG    BIT            NOT NULL CONSTRAINT DF_EMP_USER_DEL_FLG DEFAULT (0), -- 0活動 1停用
        CRT_DATE   DATETIME       NOT NULL,
        CRT_USER   NVARCHAR(10)   NOT NULL,
        MDF_DATE   DATETIME       NULL,
        MDF_USER   NVARCHAR(10)   NULL,
        CONSTRAINT PK_EMP_USER PRIMARY KEY CLUSTERED (USER_ID),
        CONSTRAINT FK_EMP_USER_EMP_ORG FOREIGN KEY (DPT_CODE)
            REFERENCES dbo.EMP_ORG (DPT_CODE)
    );
END
GO

/* ---------- 既有庫升級：補 EMP_USER.DPT_CODE 與 FK ---------- */
IF OBJECT_ID(N'dbo.EMP_USER', N'U') IS NOT NULL
   AND COL_LENGTH(N'dbo.EMP_USER', N'DPT_CODE') IS NULL
BEGIN
    ALTER TABLE dbo.EMP_USER ADD DPT_CODE NVARCHAR(10) NULL;
END
GO

IF OBJECT_ID(N'dbo.EMP_USER', N'U') IS NOT NULL
   AND OBJECT_ID(N'dbo.EMP_ORG', N'U') IS NOT NULL
   AND COL_LENGTH(N'dbo.EMP_USER', N'DPT_CODE') IS NOT NULL
   AND OBJECT_ID(N'dbo.FK_EMP_USER_EMP_ORG', N'F') IS NULL
BEGIN
    ALTER TABLE dbo.EMP_USER
        ADD CONSTRAINT FK_EMP_USER_EMP_ORG FOREIGN KEY (DPT_CODE)
            REFERENCES dbo.EMP_ORG (DPT_CODE);
END
GO

/* ---------- DIM_ROLE：角色維護主檔（EMPSet R／RoleFunctionSet R；IT 維護） ---------- */
IF OBJECT_ID(N'dbo.DIM_ROLE', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.DIM_ROLE
    (
        ROLE_ID      VARCHAR(30)    NOT NULL,
        ROLE_NAME    NVARCHAR(50)   NOT NULL,
        SYSTEM_CODE  VARCHAR(20)    NOT NULL CONSTRAINT DF_DIM_ROLE_SYSTEM_CODE DEFAULT ('PGM'),
        DEL_FLG      BIT            NOT NULL CONSTRAINT DF_DIM_ROLE_DEL_FLG DEFAULT (0),
        CRT_DATE     DATETIME       NOT NULL,
        CRT_USER     NVARCHAR(10)   NOT NULL,
        MDF_DATE     DATETIME       NULL,
        MDF_USER     NVARCHAR(10)   NULL,
        CONSTRAINT PK_DIM_ROLE PRIMARY KEY CLUSTERED (ROLE_ID)
    );

    CREATE NONCLUSTERED INDEX IX_DIM_ROLE_SYSTEM_CODE
        ON dbo.DIM_ROLE (SYSTEM_CODE, DEL_FLG, ROLE_ID);
END
GO

/* 既有庫：補 SYSTEM_CODE（亦見 20_dbo_system_code.sql） */
IF OBJECT_ID(N'dbo.DIM_ROLE', N'U') IS NOT NULL
   AND COL_LENGTH(N'dbo.DIM_ROLE', N'SYSTEM_CODE') IS NULL
BEGIN
    ALTER TABLE dbo.DIM_ROLE ADD SYSTEM_CODE VARCHAR(20) NOT NULL
        CONSTRAINT DF_DIM_ROLE_SYSTEM_CODE DEFAULT ('PGM');
END
GO

/* ---------- MAP_USER_ROLE：人員角色對應檔 ---------- */
