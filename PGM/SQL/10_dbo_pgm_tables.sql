        ON dbo.CHANGE_PASSWORD_HISTORY (USER_ID, LOG_DATE DESC);
END
GO

/* ---------- AUTHENTICATION_LOG：登入／登出軌跡（非 BMW LIST；Login 流程必要） ---------- */
IF OBJECT_ID(N'dbo.AUTHENTICATION_LOG', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.AUTHENTICATION_LOG
    (
        GUID              VARCHAR(36)    NOT NULL,
        USER_ID           VARCHAR(10)    NOT NULL,
        IDENTITY_CONTENT  NVARCHAR(500)  NULL,
        IP                NVARCHAR(50)   NULL,
        LOGIN_TYPE        CHAR(1)        NOT NULL,
